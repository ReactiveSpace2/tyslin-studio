// Writes the agency table in README.md from src/shared/agencies/ (between the agencies:start/end markers).
// Run after changing a template: node scripts/readme-agencies.mjs
import { build } from 'esbuild'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const root = resolve(import.meta.dirname, '..')
const dir = await mkdtemp(join(tmpdir(), 'tyslin-readme-'))
try {
  const out = join(dir, 'agencies.mjs')
  await build({ entryPoints: [join(root, 'src/shared/agencies.ts')], bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error' })
  const { AGENCY_TEMPLATES } = await import(pathToFileURL(out).href)
  const cell = (s) => String(s).replace(/\|/g, '\\|')
  const rows = AGENCY_TEMPLATES.map((t) => `| ${cell(t.name)} | ${cell(t.tagline)} | ${cell(t.roster.find((m) => m.lead)?.first ?? '')} | ${t.roster.length} |`)
  const table = ['| Agency | What it does | Lead | Agents |', '|---|---|---|---|', ...rows].join('\n')
  const readmePath = join(root, 'README.md')
  const readme = await readFile(readmePath, 'utf8')
  const start = '<!-- agencies:start (generated by scripts/readme-agencies.mjs) -->'
  const end = '<!-- agencies:end -->'
  const a = readme.indexOf(start), b = readme.indexOf(end)
  if (a < 0 || b < a) throw new Error('README.md has no agencies:start/end markers')
  await writeFile(readmePath, readme.slice(0, a + start.length) + '\n' + table + '\n' + readme.slice(b))
  console.log(`README.md: ${rows.length} agencies`)
} finally {
  await rm(dir, { recursive: true, force: true })
}
